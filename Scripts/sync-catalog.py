#!/usr/bin/env python3
"""Regenerate Sources/LLMKit/Resources/models.json from pi-ai's generated catalog.

pi-ai keeps one JSON file per provider under `providers/data/` (generated by its
`scripts/generate-models.ts`, shipped in the npm package under `dist/providers/data/`).
This script flattens those files into one array of chat models whose wire format
LLMKit implements, sorted for stable diffs. It also writes providers.json, each
provider's display name and models.dev logo id, read once from models.dev's API.

Usage: Scripts/sync-catalog.py <pi-ai providers/data directory>
"""

import json
import pathlib
import sys
import urllib.request

SUPPORTED_APIS = {
    "openai-completions",
    "openai-responses",
    "openai-codex-responses",
    "anthropic-messages",
    "google-generative-ai",
}

source = pathlib.Path(sys.argv[1])
resources = pathlib.Path(__file__).resolve().parent.parent / "Sources/LLMKit/Resources"
target = resources / "models.json"

# pi-ai providers that models.dev lists under another id, or not at all: (name, models.dev logo id).
PROVIDER_OVERRIDES = {
    "ant-ling": ("Ant Ling", "bailing"),
    "fireworks": ("Fireworks AI", "fireworks-ai"),
    "kimi-coding": ("Kimi For Coding", "kimi-code-plan-global"),
    "openai-codex": ("OpenAI Codex", "openai"),
    "qwen-token-plan": ("Qwen Token Plan", "alibaba-token-plan"),
    "qwen-token-plan-cn": ("Qwen Token Plan (China)", "alibaba-token-plan"),
    "qwen-token-plan-individual": ("Qwen Token Plan (Individual)", "alibaba-token-plan"),
    "together": ("Together AI", "togetherai"),
    "vercel-ai-gateway": ("Vercel AI Gateway", "vercel"),
    "zai-coding-cn": ("Z.AI Coding Plan (China)", "zhipuai-coding-plan"),
}

models = [
    model
    for path in sorted(source.glob("*.json"))
    for api, group in json.loads(path.read_text()).items()
    if api in SUPPORTED_APIS
    for model in group.values()
    if model.get("type", "chat") == "chat"
]
models.sort(key=lambda model: (model["provider"], model["id"]))
target.write_text(json.dumps(models, indent=1, sort_keys=True, ensure_ascii=False) + "\n")
print(f"{len(models)} models -> {target}")

with urllib.request.urlopen("https://models.dev/api.json") as response:
    models_dev = json.load(response)
providers = {}
for provider in sorted({model["provider"] for model in models}):
    if provider in PROVIDER_OVERRIDES:
        name, logo = PROVIDER_OVERRIDES[provider]
    elif provider in models_dev:
        name, logo = models_dev[provider]["name"], provider
    else:
        sys.exit(f"No models.dev entry for provider {provider}; add it to PROVIDER_OVERRIDES")
    providers[provider] = {"name": name, "logo": logo}
(resources / "providers.json").write_text(json.dumps(providers, indent=1, ensure_ascii=False) + "\n")
print(f"{len(providers)} providers -> {resources / 'providers.json'}")
