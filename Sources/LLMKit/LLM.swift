import Foundation

/// One Swift API over every supported LLM wire format.
///
/// ```swift
/// let model = ModelCatalog.builtin.model(provider: "anthropic", id: "claude-sonnet-4-5")!
/// let context = Context(systemPrompt: "Be brief.", messages: [.user(UserMessage("Hi"))])
/// for await event in LLM.stream(model: model, context: context, options: StreamOptions(reasoning: .medium)) {
///     if case .textDelta(_, let delta) = event { print(delta, terminator: "") }
/// }
/// ```
public enum LLM {
    /// Streams one assistant response. Failures never throw: they end the stream with `.error`.
    public static func stream(model: Model, context: Context, options: StreamOptions = StreamOptions()) -> AssistantMessageStream {
        let (events, continuation) = AsyncStream.makeStream(of: AssistantMessageEvent.self)
        let task = Task {
            let builder = ResponseBuilder(model: model, continuation: continuation)
            do {
                let transcript = Transcript.normalize(context)
                var model = model
                var options = options
                // The environment is ambient auth, as in pi-ai's resolveProviderAuth and envApiKeyAuth: an
                // explicit key skips the stored credential, a stored sign-in owns the provider, and only a
                // missing or empty key falls through to the environment.
                var useEnvironment = options.apiKey?.isEmpty ?? true
                if options.apiKey == nil, let resolveAuth = options.resolveAuth, let auth = try await resolveAuth(model) {
                    useEnvironment = auth.apiKey?.isEmpty == true
                    options.apiKey = auth.apiKey
                    options.headers = auth.headers.mapValues(Optional.some).merging(options.headers) { $1 }
                    if let baseURL = auth.baseURL { model.baseURL = baseURL }
                }
                // OpenCode routes each conversation by a required session header (pi-ai's opencode-headers).
                if ["opencode", "opencode-go"].contains(model.provider), let sessionId = options.sessionId,
                    !options.headers.keys.contains(where: { $0.lowercased() == "x-opencode-session" })
                {
                    options.headers["x-opencode-session"] = sessionId
                }
                let resolved = ResolvedOptions(model: model, transcript: transcript, options: options, useEnvironment: useEnvironment)
                switch model.api {
                case .openAICompletions:
                    try await OpenAICompletions.run(model: model, transcript: transcript, options: resolved, builder: builder)
                case .openAIResponses:
                    try await OpenAIResponses.run(model: model, transcript: transcript, options: resolved, builder: builder)
                case .openAICodexResponses:
                    try await OpenAICodexResponses.run(model: model, transcript: transcript, options: resolved, builder: builder)
                case .anthropicMessages:
                    try await AnthropicMessages.run(model: model, transcript: transcript, options: resolved, builder: builder)
                case .googleGenerativeAI:
                    try await GoogleGenerativeAI.run(model: model, transcript: transcript, options: resolved, builder: builder)
                default:
                    throw LLMError.unsupportedAPI(model.api)
                }
                try builder.complete()
            } catch {
                builder.fail(error)
            }
            continuation.finish()
        }
        continuation.onTermination = { _ in task.cancel() }
        return AssistantMessageStream(events: events)
    }

    /// Runs one request to completion. Returns the final message, which carries `stopReason`
    /// `.error` or `.aborted` and an `errorMessage` when the request failed.
    public static func complete(model: Model, context: Context, options: StreamOptions = StreamOptions()) async throws -> AssistantMessage {
        try await stream(model: model, context: context, options: options).result()
    }
}

/// A provider's display name and its logo on models.dev.
public struct ProviderInfo: Codable, Sendable, Hashable {
    /// Display name, e.g. `DeepSeek`.
    public var name: String
    /// The models.dev provider id whose logo is at `https://models.dev/logos/<logo>.svg`.
    public var logo: String

    public init(name: String, logo: String) {
        self.name = name
        self.logo = logo
    }
}

/// A model catalog generated by pi-ai. `builtin` is the snapshot bundled with LLMKit; `download`
/// fetches a published one, which the app can `write` and later reload with `init(contentsOf:)`.
/// LLMKit never refreshes on its own: when and how often is the app's decision.
public struct ModelCatalog: Sendable {
    public let models: [Model]
    /// Keyed by provider id. Always the bundled table; providers missing from it fall back to their id.
    public let providerInfo: [String: ProviderInfo]
    /// The pi-ai version the catalog was generated by.
    public let version: String?
    /// When pi-ai generated the catalog (its data manifest's `generatedAt`).
    public let generatedAt: Date?

    public init(
        models: [Model],
        providerInfo: [String: ProviderInfo] = [:],
        version: String? = nil,
        generatedAt: Date? = nil
    ) {
        self.models = models
        self.providerInfo = providerInfo
        self.version = version
        self.generatedAt = generatedAt
    }

    /// The on-disk form; `generatedAt` keeps pi-ai's ISO 8601 string with fractional seconds.
    private struct Snapshot: Codable {
        var version: String?
        var generatedAt: String?
        var models: [Model]
    }

    private static func timestampFormatter() -> ISO8601DateFormatter {
        let formatter = ISO8601DateFormatter()
        formatter.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        return formatter
    }

    private static let bundledProviderInfo: [String: ProviderInfo] = {
        guard let url = Bundle.module.url(forResource: "providers", withExtension: "json"),
            let data = try? Data(contentsOf: url),
            let info = try? JSONDecoder().decode([String: ProviderInfo].self, from: data)
        else {
            assertionFailure("The bundled providers.json is missing or malformed")
            return [:]
        }
        return info
    }()

    public static let builtin: ModelCatalog = {
        guard let url = Bundle.module.url(forResource: "models", withExtension: "json"),
            let catalog = try? ModelCatalog(contentsOf: url)
        else {
            assertionFailure("The bundled models.json is missing or malformed")
            return ModelCatalog(models: [], providerInfo: bundledProviderInfo)
        }
        return catalog
    }()

    /// Loads a snapshot saved by `write(to:)` (or the bundled one).
    public init(contentsOf url: URL) throws {
        let snapshot = try JSONDecoder().decode(Snapshot.self, from: Data(contentsOf: url))
        self.init(
            models: snapshot.models,
            providerInfo: Self.bundledProviderInfo,
            version: snapshot.version,
            generatedAt: snapshot.generatedAt.flatMap(Self.timestampFormatter().date)
        )
    }

    public func write(to url: URL) throws {
        let snapshot = Snapshot(
            version: version,
            generatedAt: generatedAt.map(Self.timestampFormatter().string),
            models: models
        )
        try JSONEncoder().encode(snapshot).write(to: url, options: .atomic)
    }

    private static let packagePath = "npm/@earendil-works/pi-ai"
    private static let supportedAPIs: Set<API> = [
        .openAICompletions, .openAIResponses, .openAICodexResponses, .anthropicMessages, .googleGenerativeAI,
    ]

    /// The newest published pi-ai version: one small request to jsDelivr's resolver. Compare it with
    /// `version` before calling `download`.
    public static func latestVersion(session: URLSession = .shared) async throws -> String {
        struct Resolved: Decodable { var version: String }
        let data = try await fetch("https://data.jsdelivr.com/v1/packages/\(packagePath)/resolved", session: session)
        return try JSONDecoder().decode(Resolved.self, from: data).version
    }

    /// Downloads the catalog pi-ai `version` publishes (`dist/providers/data`) from jsDelivr's
    /// immutable versioned URLs, keeping the chat models on wire formats LLMKit implements,
    /// exactly as `Scripts/sync-catalog.py` does for the bundled snapshot.
    public static func download(version: String, session: URLSession = .shared) async throws -> ModelCatalog {
        struct Manifest: Decodable {
            var generatedAt: String?
            var files: [String: String]
        }
        let base = "https://cdn.jsdelivr.net/\(packagePath)@\(version)/dist/providers/data/"
        let manifest = try JSONDecoder().decode(
            Manifest.self, from: try await fetch(base + ".manifest.json", session: session))
        let models = try await withThrowingTaskGroup(of: [Model].self) { group in
            for file in manifest.files.keys {
                group.addTask {
                    let groups = try JSONDecoder().decode(
                        [String: [String: JSONValue]].self, from: try await fetch(base + file, session: session))
                    return try groups
                        .filter { supportedAPIs.contains(API(rawValue: $0.key)) }
                        .flatMap(\.value.values)
                        .filter { ($0["type"]?.stringValue ?? "chat") == "chat" }
                        .map { try JSONDecoder().decode(Model.self, from: $0.data()) }
                }
            }
            return try await group.reduce(into: []) { $0 += $1 }
        }
        return ModelCatalog(
            models: models.sorted { ($0.provider, $0.id) < ($1.provider, $1.id) },
            providerInfo: bundledProviderInfo,
            version: version,
            generatedAt: manifest.generatedAt.flatMap(timestampFormatter().date)
        )
    }

    private static func fetch(_ string: String, session: URLSession) async throws -> Data {
        guard let url = URL(string: string) else { throw LLMError.invalidRequest("Invalid catalog URL: \(string)") }
        let (data, response) = try await session.data(from: url)
        let status = (response as? HTTPURLResponse)?.statusCode ?? 0
        guard status == 200 else {
            throw LLMError.http(status: status, message: "Catalog download failed: \(string)", headers: [:])
        }
        return data
    }

    public var providers: [String] {
        Array(Set(models.map(\.provider))).sorted()
    }

    public func models(provider: String) -> [Model] {
        models.filter { $0.provider == provider }
    }

    public func model(provider: String, id: String) -> Model? {
        models.first { $0.provider == provider && $0.id == id }
    }
}
